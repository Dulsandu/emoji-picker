'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict'),asar=require('@electron/asar');
const root=path.resolve(__dirname,'..');
const build=path.join(root,'dist','v1.2-p2','build');
const publicDir=path.join(root,'dist','v1.2-p2','public');
const archive=path.join(build,'win-unpacked','resources','app.asar');
const nativeHelper=path.join(build,'win-unpacked','resources','native','WindowsBridge.exe');
const artifacts=['Emoji Picker P2 Setup 1.2.0-p2.exe','Emoji Picker P2 1.2.0-p2 Portable.exe'];
const sha=data=>crypto.createHash('sha256').update(data).digest('hex');
const read=file=>asar.extractFile(archive,file.replaceAll('/','\\'));
assert(fs.existsSync(archive),'Missing app.asar');
assert(fs.existsSync(nativeHelper),'Missing native helper');
const entries=asar.listPackage(archive).map(file=>file.replaceAll('\\','/').replace(/^\//,''));
const pkg=JSON.parse(read('package.json'));
const artwork=JSON.parse(read('data/artwork-manifest.json'));
assert.equal(pkg.version,'1.2.0-p2');
assert.equal(pkg.productName,undefined);
assert.equal(artwork.mapped,3979);
assert.deepEqual(artwork.missing,[]);
for(const [file,hash] of Object.entries(artwork.files))assert.equal(sha(read('assets/emoji/'+file)),hash,file);
const emojiData=JSON.parse(read('data/emojis.json'));
assert.equal(emojiData.emojis.filter(item=>item.countryCode).length,259);
for(const file of ['main.js','preload.js','src/renderer.js','src/windowed-grid.js','src/model.js','src/styles.css','src/index.html','data/emojis.json','data/emoji-data.js','data/artwork.js','PUBLIC-README.md','LICENSE','licenses/THIRD-PARTY.md','licenses/Twemoji-CC-BY-4.0.txt','licenses/Emojibase-MIT.txt','licenses/Unicode-LICENSE.txt','licenses/koffi-LICENSE.txt']){
 assert(entries.includes(file),`Missing ${file}`);
 assert.equal(sha(read(file)),sha(fs.readFileSync(path.join(root,...file.split('/')))),file);
}
const forbiddenPaths=entries.filter(file=>/(^|\/)(tests?|scripts?|evidence|backups?|test-results|reports?)(\/|$)|(^|\/)(README|CHANGELOG|V1\.2-P\d-REPORT)\.md$|\.(map|pdb|log)$|builder-debug\.yml/i.test(file));
assert.deepEqual(forbiddenPaths,[],'Internal artifact packaged: '+forbiddenPaths.join(', '));
const koffiEntries=entries.filter(file=>file.startsWith('node_modules/koffi/')||file.startsWith('node_modules/@koromix/koffi-win32-x64/'));
const allowedKoffi=new Set([
 'node_modules/koffi/src','node_modules/koffi/src/koffi','node_modules/koffi/src/koffi/src',
 'node_modules/koffi/LICENSE.txt','node_modules/koffi/index.cjs','node_modules/koffi/package.json',
 'node_modules/koffi/src/koffi/index.cjs','node_modules/koffi/src/koffi/src/static.cjs',
 'node_modules/@koromix/koffi-win32-x64/win32_x64',
 'node_modules/@koromix/koffi-win32-x64/index.js','node_modules/@koromix/koffi-win32-x64/package.json','node_modules/@koromix/koffi-win32-x64/win32_x64/koffi.node'
]);
assert.deepEqual(koffiEntries.filter(file=>!allowedKoffi.has(file)),[],'Unexpected Koffi payload');
for(const file of allowedKoffi)assert(entries.includes(file),`Required Koffi runtime missing: ${file}`);
const projectText=entries.filter(file=>/^(main\.js|preload\.js|src\/.*\.(?:js|cjs|css|html)|PUBLIC-README\.md|package\.json|LICENSE)$/.test(file));
const provenance=/ChatGPT|OpenAI|Codex|GPT(?:-6)?|Astra|AI[- ]generated|generated by AI|conversation text|prompt text|[A-Z]:\\Users\\|oshadhs/i;
const hits=[];
for(const file of projectText){const text=read(file).toString('utf8');if(/sourceMappingURL/i.test(text))hits.push({file,term:'sourceMappingURL'});const match=text.match(provenance);if(match)hits.push({file,term:match[0]});}
const helperText=fs.readFileSync(nativeHelper).toString('latin1');const helperMatch=helperText.match(provenance);if(helperMatch)hits.push({file:'resources/native/WindowsBridge.exe',term:helperMatch[0]});
assert.deepEqual(hits,[],'Project provenance/privacy string found: '+JSON.stringify(hits));
const allowedPublic=new Set([...artifacts,'README.md','SHA256SUMS.txt','release-manifest.json']);
assert.deepEqual(fs.readdirSync(publicDir).filter(file=>!allowedPublic.has(file)),[],'Unexpected public file');
for(const file of allowedPublic)assert(fs.existsSync(path.join(publicDir,file)),`Missing public file: ${file}`);
const artifactRecords=artifacts.map(file=>{const built=path.join(build,file),released=path.join(publicDir,file);assert.equal(sha(fs.readFileSync(released)),sha(fs.readFileSync(built)),file);return {file,bytes:fs.statSync(released).size,sha256:sha(fs.readFileSync(released))};});
const report={version:pkg.version,verifiedAt:new Date().toISOString(),asar:{sha256:sha(fs.readFileSync(archive)),entries:entries.length,artworkFiles:Object.keys(artwork.files).length,countryFlags:259,koffiFiles:koffiEntries.sort()},projectProvenanceHits:hits,publicFiles:[...allowedPublic].sort(),artifacts:artifactRecords};
const evidence=path.join(root,'evidence','v1.2-p2');fs.mkdirSync(evidence,{recursive:true});
fs.writeFileSync(path.join(evidence,'artifact-verification.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
